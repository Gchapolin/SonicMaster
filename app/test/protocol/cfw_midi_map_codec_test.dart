List<MidiMapEntry> _rows() => [
  for (final b in _captured) MidiMapEntry.fromBytes(b),
];

/// The payloads of [frames], multi-packet messages joined.
List<List<int>> _payloads(List<String> frames) {
  final out = <List<int>>[];

  for (final f in frames) {
    final b = collapseFrame(f)!;

    if (b[2] == 0) {
      out.add([...b.sublist(4)]);
    } else {
      out.last.addAll(b.sublist(4));
    }
  }

  return out;
}

void main() {
  test('the checksum matches the four captured maps', () {
    expect(midiMapCrc(0, const []), 0x1cfa);
    expect(midiMapCrc(1, const []), 0xdcab);
    expect(
      midiMapCrc(0, [
        MidiMapEntry.fromBytes(const [1, 0, 0, 0, 0, 5, 0, 0]),
      ]),
      0xf2d2,
    );
    expect(midiMapCrc(3, _rows()), 0x0e43);
  });

  test('an empty map is the header and the commit, as captured', () {
    expect(buildMidiMapFrames(options: 1, entries: const []), [
      buildSysexWriteFrame([
        0x11, 0x39, 0x00, 0x50, 0x4d, 0x4d, 0x4d, 0x01, 0x01, 0x00, 0x00, //
        0x00, 0x00, 0x00, 0x00, 0xab, 0xdc, 0x00, 0x00,
      ]),
      buildSysexWriteFrame([0x11, 0x39, 0x02, 0xab, 0xdc]),
    ]);
  });

  test('34 rows go out as the captured header, five batches and commit', () {
    final frames = buildMidiMapFrames(options: 3, entries: _rows());
    final payloads = _payloads(frames);

    expect(frames, hasLength(1 + 4 + 4 + 4 + 4 + 2 + 1));
    expect(payloads.first, [
      0x11, 0x39, 0x00, 0x50, 0x4d, 0x4d, 0x4d, 0x01, 0x03, 0x22, 0x00, //
      0x00, 0x00, 0x00, 0x00, 0x43, 0x0e, 0x00, 0x00,
    ]);
    expect(payloads[1].sublist(0, 13), [
      0x11, 0x39, 0x01, 0x00, 0x08, ..._captured[0], //
    ]);
    expect(payloads[1], hasLength(5 + 64));
    expect(payloads[5], [
      0x11, 0x39, 0x01, 0x20, 0x02, ..._captured[32], ..._captured[33], //
    ]);
    expect(payloads.last, [0x11, 0x39, 0x02, 0x43, 0x0e]);
  });

  test('the read frames and their replies', () {
    expect(readMidiMapInfoFrame(), buildSysexWriteFrame([0x12, 0x39, 0x00]));
    expect(
      readMidiMapPageFrame(16),
      buildSysexWriteFrame([0x12, 0x39, 0x01, 0x10]),
    );

    // Captured info reply with 34 rows, options 3.
    final info = decodeMidiMapInfo(
      buildSysexWriteFrame([
        0x12, 0x39, 0x00, 0x01, 0x01, 0x81, 0x22, 0x40, 0x03, 0x03, 0x00, //
        0x00, 0x00, 0x43, 0x0e, 0x01, 0x9b, 0x14, 0x04, 0x88, 0x4b, 0x00,
        0x00, 0xbc, 0x3c, 0x00, 0x00,
      ]),
    )!;

    expect(info.count, 34);
    expect(info.options, 3);
    expect(info.crc, 0x0e43);

    final page = decodeMidiMapPage(
      buildSysexWriteFrame([
        0x12, 0x39, 0x01, 0x20, 0x02, ..._captured[32], ..._captured[33], //
      ]),
    )!;

    expect(page.first, 0x20);
    expect(page.entries, [_rows()[32], _rows()[33]]);
  });

  test('truncated or foreign replies decode to null', () {
    expect(decodeMidiMapInfo(buildSysexWriteFrame([0x12, 0x39, 0])), isNull);
    expect(
      decodeMidiMapPage(buildSysexWriteFrame([0x12, 0x39, 1, 0, 2, 1, 0, 0])),
      isNull,
    );
    expect(
      decodeMidiMapPage(buildSysexWriteFrame([0x12, 0x39, 0, 0, 0])),
      isNull,
    );
    expect(decodeMidiMapInfo('nope'), isNull);
  });

  test('optionLabel is the picked options, null without any', () {
    const bank = MidiMapEntry(from: 101, to: 102, function: 2);

    expect(bank.optionLabel(), 'Bank −, Bank +');
    expect(const MidiMapEntry(function: 5).optionLabel(), isNull);
  });

  test('a row describes itself like the web app', () {
    final rows = _rows();

    expect(rows[2].describe(), 'PC 101–102 → Bank −, Bank +');
    expect(rows[4].describe(), 'PC 105 → Tap tempo');
    expect(
      rows[5].describe(),
      'PC 106 → Looper rec / play / clear: Rec / Play',
    );
    expect(rows[19].describe(), 'CC 43–51 → Block on / off: NR … RVB');
    expect(rows[0].describe(), 'PC 1–100 → Select preset: P01 … F50');
  });

  test('value and switch read as on the wire', () {
    expect(MidiMapEntry.valueLabel(0), 'any');
    expect(MidiMapEntry.valueLabel(1), '≥ 64');
    expect(MidiMapEntry.valueLabel(2), '< 64');
    expect(MidiMapEntry.valueLabel(0x80 | 42), '= 42');
    expect(_rows()[8].hasSwitch, isTrue); // Freeze
    expect(_rows()[4].hasSwitch, isFalse); // Tap tempo
  });
}
